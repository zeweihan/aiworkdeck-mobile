/** 全部生成物：相对路径 → 内容 */
export function outputs(c) {
  const kt = 'android/contract/src/main/kotlin/com/aiworkdeck/contract'
  const ets = 'harmony/contract/src/main/ets'
  return new Map([
    ['miniprogram/styles/tokens.wxss', renderWxss(c)],
    ['miniprogram/utils/contract/states.ts', renderTsStates(c)],
    ['miniprogram/utils/contract/strings.ts', renderTsStrings(c)],
    ['miniprogram/utils/contract/capabilities.ts', renderTsCaps(c, 'miniprogram')],
    ['ios/Sources/Contract/Tokens.swift', renderSwiftTokens(c)],
    ['ios/Sources/Contract/Strings.swift', renderSwiftStrings(c)],
    ['ios/Sources/Contract/States.swift', renderSwiftStates(c)],
    ['ios/Sources/Contract/Capabilities.swift', renderSwiftCaps(c)],
    [`${kt}/Tokens.kt`, renderKtTokens(c)],
    [`${kt}/Strings.kt`, renderKtStrings(c)],
    [`${kt}/States.kt`, renderKtStates(c)],
    [`${kt}/Capabilities.kt`, renderKtCaps(c)],
    [`${ets}/Tokens.ets`, renderEtsTokens(c)],
    [`${ets}/Strings.ets`, renderEtsStrings(c)],
    [`${ets}/States.ets`, renderEtsStates(c)],
    [`${ets}/Capabilities.ets`, renderEtsCaps(c)],
  ])
}
